export const matchAll = (rules, value) => rules.filter(([re]) => re.test(value)).map(([, name]) => name);
export const uniq = (arr) => [...new Set(arr)];

export function hostingFromOrg(org) {
  return org ? (HOSTING_BY_ORG.find(([re]) => re.test(org))?.[1] || org) : null;
}

/** Splits a Team Cymru origin TXT ("13335 | 1.1.1.0/24 | US | arin | 2010-07-14") into fields. */
export function parseCymruOrigin(txt) {
  const [asn, prefix, country, registry] = txt.split('|').map((x) => x.trim());
  return { asn: Number(asn.split(' ')[0]), prefix, country, registry };
}

export function parseCymruAsName(txt) {
  return txt ? txt.split('|').at(-1).trim().replace(/,\s*[A-Z]{2}$/, '') : null;
}
